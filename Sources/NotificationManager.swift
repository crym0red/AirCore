//
//  NotificationManager.swift
//  Certificate expiry notifications and alerts.
//

import Foundation
import UIKit
import UserNotifications

extension Notification.Name {
    static let airshareOpenDeepLink = Notification.Name("airshareOpenDeepLink")
}

@MainActor
final class NotificationManager: NSObject, ObservableObject, UNUserNotificationCenterDelegate {
    static let shared = NotificationManager()

    private let installNotificationsKey = "msign.installReadyNotifications"

    var notificationsEnabled: Bool { installReadyNotificationsEnabled }

    var installReadyNotificationsEnabled: Bool {
        get {
            if UserDefaults.standard.object(forKey: installNotificationsKey) == nil { return true }
            return UserDefaults.standard.bool(forKey: installNotificationsKey)
        }
        set { UserDefaults.standard.set(newValue, forKey: installNotificationsKey) }
    }

    private override init() {
        super.init()
        UNUserNotificationCenter.current().delegate = self
        requestAuthorization()
    }
    
    func requestAuthorization() {
        UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .sound, .badge]) { granted, error in
            if granted {
                DispatchQueue.main.async {
                    UIApplication.shared.registerForRemoteNotifications()
                }
            }
        }
    }
    
    // MARK: - Notification → deep-link routing

    /// Notifications can carry an AirShare deep link. This works for both local
    /// notifications generated by AirShare and APNs payloads sent by a server.
    nonisolated func userNotificationCenter(_ center: UNUserNotificationCenter,
                                            didReceive response: UNNotificationResponse,
                                            withCompletionHandler completionHandler: @escaping () -> Void) {
        let userInfo = response.notification.request.content.userInfo
        // "Reconnect VPN" reminder left by the native installer.
        if response.actionIdentifier == UNNotificationDefaultActionIdentifier,
           let id = userInfo["ksignVPNReconnectID"] as? String,
           response.notification.request.identifier == VPNReconnectCoordinator.notificationIdentifier + "." + id {
            Task { @MainActor in
                await VPNReconnectCoordinator.shared.notificationTapped(id: id)
                completionHandler()
            }
            return
        }
        guard let raw = userInfo["deepLink"] as? String, let url = URL(string: raw) else {
            completionHandler()
            return
        }
        Task { @MainActor in
            NotificationCenter.default.post(name: .airshareOpenDeepLink, object: url)
            completionHandler()
        }
    }

    nonisolated func userNotificationCenter(_ center: UNUserNotificationCenter,
                                            willPresent notification: UNNotification,
                                            withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void) {
        completionHandler([.banner, .sound, .badge])
    }

    /// Notify the user when a locally signed IPA is ready. Tapping the
    /// notification opens AirShare's deep link, which hands the signed IPA to
    /// OTAInstaller and presents the normal iOS itms-services install prompt.
    func scheduleInstallReadyNotification(for entry: SignedEntry) {
        guard installReadyNotificationsEnabled else { return }
        let deepLink = "airshare://install?signedID=\(entry.id)"
        let content = UNMutableNotificationContent()
        content.title = "\(entry.name) is ready"
        content.body = "Tap to open AirShare and install the signed app."
        content.sound = .default
        content.userInfo = [
            "deepLink": deepLink,
            "type": "install-ready",
            "signedID": entry.id
        ]
        let trigger = UNTimeIntervalNotificationTrigger(timeInterval: 1.0, repeats: false)
        let request = UNNotificationRequest(
            identifier: "install-ready-\(entry.id)",
            content: content,
            trigger: trigger
        )
        UNUserNotificationCenter.current().add(request) { error in
            if let error { print("Failed to schedule install-ready notification: \(error.localizedDescription)") }
        }
    }

    /// Notify when a monitored source publishes a newer version.
    func scheduleSourceUpdateNotification(source: RepoSource, app: SourceApp, previousVersion: String) {
        guard notificationsEnabled else { return }
        let content = UNMutableNotificationContent()
        content.title = "\(app.name) \(app.version) is available"
        content.body = "A new version was found in \(source.name). Open AirShare to update."
        content.sound = .default
        content.userInfo = [
            "type": "source-update",
            "sourceID": source.id,
            "bundleID": app.bundle,
            "version": app.version,
            "previousVersion": previousVersion,
            "deepLink": "airshare://updates?sourceID=\(source.id)&bundleID=\(app.bundle.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? app.bundle)"
        ]
        let request = UNNotificationRequest(identifier: "source-update-\(source.id)-\(app.bundle)-\(app.version)", content: content, trigger: UNTimeIntervalNotificationTrigger(timeInterval: 1, repeats: false))
        UNUserNotificationCenter.current().add(request) { error in
            if let error { print("Failed to schedule source update notification: \(error.localizedDescription)") }
        }
    }

    func scheduleSourceUpdateFailedNotification(app: SourceApp, reason: String) {
        guard notificationsEnabled else { return }
        let content = UNMutableNotificationContent()
        content.title = "Update signing failed"
        content.body = "AirShare found \(app.name) \(app.version), but automatic signing failed. Tap to review AirShare."
        content.sound = .default
        content.userInfo = ["type": "source-update-failed", "deepLink": "airshare://updates?bundleID=\(app.bundle.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? app.bundle)", "reason": reason]
        let request = UNNotificationRequest(identifier: "source-update-failed-\(app.bundle)-\(app.version)", content: content, trigger: UNTimeIntervalNotificationTrigger(timeInterval: 1, repeats: false))
        UNUserNotificationCenter.current().add(request) { error in
            if let error { print("Failed to schedule source update failure notification: \(error.localizedDescription)") }
        }
    }

    /// Schedule certificate expiry notifications
    func scheduleExpiryNotifications(for certificates: [Certificate]) {
        let center = UNUserNotificationCenter.current()
        center.getPendingNotificationRequests { requests in
            let certificateIDs = requests.map(\.identifier).filter { $0.hasPrefix("cert-") || $0.hasPrefix("renew-") }
            if !certificateIDs.isEmpty { center.removePendingNotificationRequests(withIdentifiers: certificateIDs) }
        }
        
        for cert in certificates {
            guard let provisionData = try? Data(contentsOf: cert.provisionURL) else { continue }
            let profileInfo = CertificateStore.profileInfo(provisionData)
            guard let expiryDate = profileInfo.expirationDate else { continue }
            
            let daysRemaining = Calendar.current.dateComponents([.day], from: Date(), to: expiryDate).day ?? 0
            
            // Schedule 7-day warning
            if daysRemaining == 7 {
                scheduleNotification(
                    title: "Certificate Expiring Soon",
                    body: "\(cert.name) expires in 7 days",
                    date: expiryDate.addingTimeInterval(-7 * 24 * 3600),
                    id: "cert-7day-\(cert.id)"
                )
            }
            
            // Schedule 1-day warning
            if daysRemaining == 1 {
                scheduleNotification(
                    title: "Certificate Expires Tomorrow",
                    body: "\(cert.name) expires tomorrow at \(expiryDate.formatted(date: .omitted, time: .shortened))",
                    date: expiryDate.addingTimeInterval(-24 * 3600),
                    id: "cert-1day-\(cert.id)"
                )
            }
            
            // Schedule expiry notification
            if daysRemaining <= 0 {
                scheduleNotification(
                    title: "Certificate Expired",
                    body: "\(cert.name) has expired and can no longer sign apps",
                    date: expiryDate,
                    id: "cert-expired-\(cert.id)"
                )
            }
        }
    }
    
    /// Schedule backup reminder (monthly)
    func scheduleBackupReminder() {
        var dateComponents = DateComponents()
        dateComponents.day = 1
        dateComponents.hour = 9
        dateComponents.minute = 0
        
        let trigger = UNCalendarNotificationTrigger(dateMatching: dateComponents, repeats: true)
        let content = UNMutableNotificationContent()
        content.title = "Monthly Backup Reminder"
        content.body = "Back up your certificates to prevent data loss"
        content.sound = .default
        content.badge = 1
        
        let request = UNNotificationRequest(identifier: "backup-reminder", content: content, trigger: trigger)
        UNUserNotificationCenter.current().add(request) { _ in }
    }
    
    /// Schedule failed signing alert
    func scheduleFailedSigningAlert(appName: String, reason: String) {
        scheduleNotification(
            title: "Signing Failed",
            body: "Failed to sign \(appName): \(reason)",
            date: Date().addingTimeInterval(2),
            id: "failed-sign-\(UUID().uuidString)"
        )
    }
    
    /// Schedule renewal reminder
    func scheduleRenewalReminder(for certificate: Certificate, daysUntilExpiry: Int) {
        if daysUntilExpiry <= 30 && daysUntilExpiry > 0 {
            scheduleNotification(
                title: "Renew Certificate",
                body: "Time to renew \(certificate.name) - expires in \(daysUntilExpiry) days",
                date: Date().addingTimeInterval(86400),
                id: "renew-\(certificate.id)"
            )
        }
    }
    
    private func scheduleNotification(title: String, body: String, date: Date, id: String) {
        let content = UNMutableNotificationContent()
        content.title = title
        content.body = body
        content.sound = .default
        content.badge = 1
        content.userInfo = ["certID": id]
        
        let trigger = UNCalendarNotificationTrigger(
            dateMatching: Calendar.current.dateComponents([.year, .month, .day, .hour, .minute], from: date),
            repeats: false
        )
        
        let request = UNNotificationRequest(identifier: id, content: content, trigger: trigger)
        UNUserNotificationCenter.current().add(request) { error in
            if let error = error {
                print("Failed to schedule notification: \(error.localizedDescription)")
            }
        }
    }
}
